package netpolicy

import (
	"encoding/json"
	"fmt"
	"strings"
)

// CNIDataDir holds host-local's address reservations. It lives under the
// EraInfra state directory so a host that also runs Docker or Kubernetes
// CNI keeps its own allocations untouched.
const CNIDataDir = "/var/lib/runner-center/cni/networks"

const cniVersion = "1.0.0"

// Conflist renders the CNI configuration list for the policy. The output is
// deterministic, so an operator can diff what is installed against what this
// build expects, and Verify can compare the two exactly.
func (p Policy) Conflist() ([]byte, error) {
	if err := p.Validate(); err != nil {
		return nil, err
	}
	ptp := map[string]any{
		"type":   "ptp",
		"ipMasq": true,
		"ipam": map[string]any{
			"type":    "host-local",
			"subnet":  p.Subnet,
			"dataDir": CNIDataDir,
			"routes":  []any{map[string]any{"dst": "0.0.0.0/0"}},
		},
		"dns": map[string]any{"nameservers": toAnySlice(p.Nameservers)},
	}
	if p.MTU > 0 {
		ptp["mtu"] = p.MTU
	}
	document := map[string]any{
		"cniVersion": cniVersion,
		"name":       p.Name,
		"plugins": []any{
			ptp,
			// The firewall plugin admits return traffic for the guest's own
			// connections. It is not what denies anything: the nftables table is.
			map[string]any{"type": "firewall", "backend": "iptables"},
			// tc-redirect-tap must run last. It converts the veth the earlier
			// plugins configured into the tap device Firecracker attaches to.
			map[string]any{"type": "tc-redirect-tap"},
		},
	}
	rendered, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("render CNI configuration: %w", err)
	}
	return append(rendered, '\n'), nil
}

// Nftables renders the table that enforces the policy.
//
// The chains hook the kernel at a priority just ahead of the filter default so
// a drop lands before another table could accept, but they keep an accept
// policy: a drop policy in this table would break every unrelated flow on a
// host that also runs Docker. Isolation therefore comes from explicit drop
// verdicts scoped to the guest subnet, which are final wherever they match.
//
// The Profile egress rules are rendered on every host, whatever its own mode.
// They match only guests the runtime puts in the per-guest sets, so a Worker
// whose Profiles are all public carries them inert, and one table serves every
// Profile a Worker prepares.
func (p Policy) Nftables() (string, error) {
	if err := p.Validate(); err != nil {
		return "", err
	}
	var builder strings.Builder
	write := func(format string, args ...any) {
		fmt.Fprintf(&builder, format, args...)
	}
	flowKey := "ip saddr . ip daddr . meta l4proto . th dport"
	write("#!/usr/sbin/nft -f\n")
	write("# Generated by EraInfra. Edit the Profile policy, not this file:\n")
	write("# runner-center-runtime preflight rejects a table that no longer matches.\n")
	write("table inet %s\n", TableName)
	write("delete table inet %s\n\n", TableName)
	write("table inet %s {\n", TableName)
	write("\tset %s {\n\t\ttype ipv4_addr\n\t\tflags interval\n\t\telements = { %s }\n\t}\n\n",
		GuestSetName, p.Subnet)
	write("\tset %s {\n\t\ttype ipv4_addr\n\t\tflags interval\n", AllowSetName)
	if allowed := p.allowedOrEmpty(); len(allowed) > 0 {
		write("\t\telements = { %s }\n", joinCIDRs(allowed))
	}
	write("\t}\n\n")
	write("\tset %s {\n\t\ttype ipv4_addr\n\t}\n\n", ObservedSetName)
	write("\tset %s {\n\t\ttype ipv4_addr\n\t}\n\n", RestrictedSetName)
	write("\tset %s {\n\t\ttype ipv4_addr . ipv4_addr\n\t\tflags interval\n\t}\n\n", AllowCIDRSetName)
	write("\tset %s {\n\t\ttype ipv4_addr . ipv4_addr\n\t\tflags timeout\n\t}\n\n", AllowDNSSetName)
	for _, name := range []string{FlowSetName, BlockedSetName} {
		// The timeout outlives the longest job a runtime accepts, so a record is
		// never lost to expiry before teardown collects it.
		write("\tset %s {\n\t\ttype ipv4_addr . ipv4_addr . inet_proto . inet_service\n"+
			"\t\tflags dynamic,timeout\n\t\ttimeout 7h\n\t\tsize %d\n\t}\n\n", name, FlowRecordCapacity)
	}

	write("\tchain forward {\n")
	write("\t\ttype filter hook forward priority filter - 10; policy accept;\n")
	write("\t\tip saddr @%s ip daddr @%s drop comment \"%s\"\n",
		GuestSetName, GuestSetName, RuleDenyEastWest)
	write("\t\tip saddr @%s ct state new meta l4proto { tcp, udp } add @%s { %s } comment \"%s\"\n",
		ObservedSetName, FlowSetName, flowKey, RuleRecordFlows)
	// The jump comes before the host's own accept so a Profile allowlist is
	// enforced even for a destination the operator excepted; a flow the
	// Profile allows returns here and still has to pass every host rule below.
	write("\t\tip saddr @%s jump %s comment \"%s\"\n",
		RestrictedSetName, RestrictedChain, RuleRestrictProfile)
	write("\t\tip saddr @%s ip daddr @%s accept comment \"%s\"\n",
		GuestSetName, AllowSetName, RuleAllowDestinations)
	write("\t\tip saddr @%s ip daddr { %s } drop comment \"%s\"\n",
		GuestSetName, joinCIDRs(deniedRanges), RuleDenyPrivate)
	if p.EgressMode == EgressAllowlist {
		write("\t\tip saddr @%s drop comment \"%s\"\n", GuestSetName, RuleDenyDefault)
	}
	write("\t}\n\n")

	// A restricted guest's packet returns to the forward chain only for a flow
	// it already has, or for a TCP or UDP destination its Profile allows: a
	// CIDR, or an address the host resolver answered for an allowed name.
	// Everything else is recorded and dropped. The established rule is what
	// keeps a long download alive after the DNS TTL that admitted it runs out.
	write("\tchain %s {\n", RestrictedChain)
	write("\t\tct state established,related return comment \"%s\"\n", RuleRestrictedEstablished)
	write("\t\tmeta l4proto { tcp, udp } ip saddr . ip daddr @%s return comment \"%s\"\n",
		AllowCIDRSetName, RuleRestrictedAllowCIDR)
	write("\t\tmeta l4proto { tcp, udp } ip saddr . ip daddr @%s return comment \"%s\"\n",
		AllowDNSSetName, RuleRestrictedAllowDNS)
	write("\t\tmeta l4proto { tcp, udp } add @%s { %s } comment \"%s\"\n",
		BlockedSetName, flowKey, RuleRecordBlocked)
	write("\t\tdrop comment \"%s\"\n", RuleRestrictedDeny)
	write("\t}\n\n")

	// An observed guest's DNS goes to the host resolver whatever server it
	// asked for. The resolver answers only allowed names for a restricted
	// guest, and records every name for an observed one.
	write("\tchain prerouting {\n")
	write("\t\ttype nat hook prerouting priority dstnat; policy accept;\n")
	write("\t\tip saddr @%s meta l4proto { tcp, udp } th dport 53 redirect to :%d comment \"%s\"\n",
		ObservedSetName, ResolverPort, RuleRedirectDNS)
	write("\t}\n\n")

	// A guest needs no host service except, when observed, the resolver its DNS
	// was redirected to. MMDS is answered by the VMM before a packet reaches the
	// host stack, and IPAM is static, so nothing else legitimate is addressed to
	// the host itself.
	write("\tchain input {\n")
	write("\t\ttype filter hook input priority filter - 10; policy accept;\n")
	write("\t\tip saddr @%s meta l4proto { tcp, udp } th dport %d accept comment \"%s\"\n",
		ObservedSetName, ResolverPort, RuleAllowResolver)
	write("\t\tip saddr @%s drop comment \"%s\"\n", GuestSetName, RuleDenyHostInput)
	write("\t}\n")
	write("}\n")
	return builder.String(), nil
}

// ChainSpec is what Verify requires of one chain: its type and hook, both
// empty for a regular chain reached only by a jump, and the exact ordered rule
// comments it holds.
type ChainSpec struct {
	Type  string
	Hook  string
	Rules []string
}

// ExpectedChains is every chain the table must contain. Verify compares it
// against the live table, so a removed rule, an inserted one, a missing chain
// and a re-hooked chain all fail readiness.
func (p Policy) ExpectedChains() map[string]ChainSpec {
	forward := []string{
		RuleDenyEastWest, RuleRecordFlows, RuleRestrictProfile, RuleAllowDestinations, RuleDenyPrivate,
	}
	if p.EgressMode == EgressAllowlist {
		forward = append(forward, RuleDenyDefault)
	}
	return map[string]ChainSpec{
		"forward": {Type: "filter", Hook: "forward", Rules: forward},
		RestrictedChain: {Rules: []string{
			RuleRestrictedEstablished, RuleRestrictedAllowCIDR, RuleRestrictedAllowDNS,
			RuleRecordBlocked, RuleRestrictedDeny,
		}},
		"prerouting": {Type: "nat", Hook: "prerouting", Rules: []string{RuleRedirectDNS}},
		"input":      {Type: "filter", Hook: "input", Rules: []string{RuleAllowResolver, RuleDenyHostInput}},
	}
}

// ExpectedRules is the rule comments of ExpectedChains, by chain.
func (p Policy) ExpectedRules() map[string][]string {
	rules := map[string][]string{}
	for name, chain := range p.ExpectedChains() {
		rules[name] = chain.Rules
	}
	return rules
}

// RuntimeSets are the per-guest sets the runtime owns. Verify requires each to
// exist but never inspects its elements, which are live guest state.
func RuntimeSets() []string {
	return []string{
		ObservedSetName, RestrictedSetName, AllowCIDRSetName, AllowDNSSetName, FlowSetName, BlockedSetName,
	}
}

func toAnySlice(values []string) []any {
	result := make([]any, 0, len(values))
	for _, value := range values {
		result = append(result, value)
	}
	return result
}
