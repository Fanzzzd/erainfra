// Writes cloudflare/modules.generated.ts: one static import per backend module, keyed the way
// Convex names functions ("infra/nodes" for convex/infra/nodes.ts). Workers cannot glob at run
// time, so the Cloudflare entry imports this list. `pnpm generate:cloudflare`; CI checks it is
// current.
import { execFileSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../convex/", import.meta.url).pathname;
const out = new URL("../cloudflare/modules.generated.ts", import.meta.url).pathname;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === "_generated" ? [] : walk(path);
    if (!name.endsWith(".ts") || name.endsWith(".d.ts") || name.endsWith(".test.ts")) return [];
    if (name === "convex.config.ts") return [];
    return [path];
  });
}

const files = walk(root)
  .map((p) => relative(root, p))
  .toSorted();
const lines = [
  "// Generated by scripts/generate-cloudflare-modules.ts. Do not edit.",
  "",
  ...files.map((f, i) => `import * as m${i} from "../convex/${f}";`),
  "",
  "export const modules: Record<string, Record<string, unknown>> = {",
  ...files.map((f, i) => `  ${JSON.stringify(f.replace(/\.ts$/, ""))}: m${i},`),
  "};",
  "",
];
writeFileSync(out, lines.join("\n"));
// oxfmt sorts imports its own way; format here so `pnpm format:check` and the CI diff agree.
execFileSync("pnpm", ["exec", "oxfmt", out], { stdio: "inherit" });
console.log(`wrote ${files.length} modules to ${relative(process.cwd(), out)}`);
