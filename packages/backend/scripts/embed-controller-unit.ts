/**
 * Regenerates `convex/controllerUnit.generated.ts` from
 * `deploy/systemd/runner-center-controller@.service`.
 *
 * `/install --role controller` writes this unit, and it has to travel inside the rendered script
 * for the same reasons the Firecracker provisioner does: the role is one curl with nothing else to
 * fetch from this deployment, and Convex bundles TypeScript, not repository files. It is a
 * separate module from the provisioner's because the two roles ship different files, and folding
 * a controller file into a module named for the Firecracker host would mislead whoever regenerates
 * it. A test asserts the module matches the repository file byte for byte, so editing the unit
 * without rerunning this fails CI instead of shipping a stale unit.
 *
 * Usage: pnpm --filter @erainfra/backend embed-controller-unit
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "..", "..", "..");
const target = path.resolve(import.meta.dirname, "..", "convex", "controllerUnit.generated.ts");

// Newline-joined 76-column lines, the same shape as the provisioner embed: the install script
// carries this inside a heredoc that `base64 -d` reads.
function constant(bytes: Buffer) {
  const lines = bytes.toString("base64").match(/.{1,76}/g) ?? [];
  return lines
    .map((line, index) => `  "${line}${index === lines.length - 1 ? "" : "\\n"}"`)
    .join(" +\n");
}

const unit = readFileSync(
  path.join(repoRoot, "deploy", "systemd", "runner-center-controller@.service"),
);
const unitSha = createHash("sha256").update(unit).digest("hex");

writeFileSync(
  target,
  `// GENERATED by scripts/embed-controller-unit.ts — do not edit.
// Source: deploy/systemd/runner-center-controller@.service (sha256 ${unitSha}).
// Regenerate with: pnpm --filter @erainfra/backend embed-controller-unit

/** \`deploy/systemd/runner-center-controller@.service\`, base64-encoded for interpolation into shell. */
export const CONTROLLER_UNIT_B64 =
${constant(unit)};

/** SHA-256 of the decoded unit file, asserted by the sync test. */
export const CONTROLLER_UNIT_SHA256 =
  "${unitSha}";
`,
);

process.stdout.write(`${path.relative(repoRoot, target)}: ${unitSha}\n`);
